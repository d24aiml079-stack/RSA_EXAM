import copy
import torch
import torch.nn as nn
import torch.nn.functional as F
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from torchvision import datasets, transforms
from torch.utils.data import DataLoader

torch.manual_seed(42)
device = torch.device("cpu")

# ---------------- Data (pixels in [0,1]) ----------------
tf = transforms.ToTensor()
train_ds = datasets.MNIST("./data", train=True, download=True, transform=tf)
test_ds = datasets.MNIST("./data", train=False, download=True, transform=tf)
train_loader = DataLoader(train_ds, batch_size=64, shuffle=True)
test_loader = DataLoader(test_ds, batch_size=1000, shuffle=False)

# ---------------- Model ----------------
class CNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(1, 32, 3)
        self.conv2 = nn.Conv2d(32, 64, 3)
        self.fc1 = nn.Linear(64 * 12 * 12, 128)
        self.fc2 = nn.Linear(128, 10)

    def forward(self, x):
        x = F.relu(self.conv1(x))
        x = F.max_pool2d(F.relu(self.conv2(x)), 2)
        x = torch.flatten(x, 1)
        x = F.relu(self.fc1(x))
        return self.fc2(x)

# ---------------- Attacks ----------------
def fgsm(model, x, y, eps):
    x = x.clone().detach().requires_grad_(True)
    loss = F.cross_entropy(model(x), y)
    grad = torch.autograd.grad(loss, x)[0]
    return torch.clamp(x + eps * grad.sign(), 0, 1).detach()

def pgd(model, x, y, eps, iters=10):
    alpha = eps / 4
    x_adv = x + torch.empty_like(x).uniform_(-eps, eps)
    x_adv = torch.clamp(x_adv, 0, 1).detach()
    for _ in range(iters):
        x_adv.requires_grad_(True)
        loss = F.cross_entropy(model(x_adv), y)
        grad = torch.autograd.grad(loss, x_adv)[0]
        x_adv = x_adv.detach() + alpha * grad.sign()
        x_adv = torch.min(torch.max(x_adv, x - eps), x + eps)
        x_adv = torch.clamp(x_adv, 0, 1).detach()
    return x_adv

# ---------------- Helpers ----------------
def train(model, epochs=2, adv_eps=None, lr=0.001):
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    for ep in range(epochs):
        for x, y in train_loader:
            x, y = x.to(device), y.to(device)
            if adv_eps is not None:
                model.eval()
                x_adv = fgsm(model, x, y, adv_eps)
                model.train()
                x = torch.cat([x, x_adv])
                y = torch.cat([y, y])
            model.train()
            opt.zero_grad()
            loss = F.cross_entropy(model(x), y)
            loss.backward()
            opt.step()
        print(f"  epoch {ep + 1}/{epochs} done, last loss = {loss.item():.4f}")

def evaluate(model, attack=None, eps=0.0):
    model.eval()
    correct = 0
    for x, y in test_loader:
        x, y = x.to(device), y.to(device)
        if attack is not None and eps > 0:
            x = attack(model, x, y, eps)
        with torch.no_grad():
            correct += (model(x).argmax(1) == y).sum().item()
    return 100.0 * correct / len(test_ds)

# =============== TASK 1: Baseline ===============
print("Training baseline CNN (2 epochs)...")
base = CNN().to(device)
train(base, epochs=2)
print("done.")
clean_acc = evaluate(base)
print(f"Clean test accuracy : {clean_acc:.1f} %\n")

# =============== TASK 2 & 3: FGSM / PGD ===============
eps_list = [0.0, 0.05, 0.10, 0.20, 0.30]
fgsm_accs, pgd_accs = [], []
print("EPSILON    FGSM_ACC    PGD_ACC")
print("-------------------------------")
for e in eps_list:
    fa = clean_acc if e == 0 else evaluate(base, fgsm, e)
    pa = clean_acc if e == 0 else evaluate(base, pgd, e)
    fgsm_accs.append(fa)
    pgd_accs.append(pa)
    print(f" {e:.2f}       {fa:5.1f} %     {pa:5.1f} %")
print("-------------------------------")

# =============== TASK 4: Clean vs adversarial digits ===============
base.eval()
xs, ys = next(iter(test_loader))
xs, ys = xs[:5], ys[:5]
xa = fgsm(base, xs, ys, 0.20)
with torch.no_grad():
    p_clean = base(xs).argmax(1)
    p_adv = base(xa).argmax(1)

fig, axes = plt.subplots(2, 5, figsize=(12, 5))
for i in range(5):
    axes[0, i].imshow(xs[i, 0], cmap="gray")
    axes[0, i].set_title(f"Clean\ntrue={ys[i].item()} pred={p_clean[i].item()}")
    axes[0, i].axis("off")
    axes[1, i].imshow(xa[i, 0], cmap="gray")
    axes[1, i].set_title(f"FGSM eps=0.20\npred={p_adv[i].item()}")
    axes[1, i].axis("off")
plt.tight_layout()
plt.savefig("clean_vs_adversarial.png", dpi=150)
plt.close()

misread = [(ys[i].item(), p_adv[i].item()) for i in range(5) if p_adv[i] != ys[i]]
print("Mis-read digits saved : clean_vs_adversarial.png")
print("Mis-read (true -> predicted):", misread if misread else "none")
i20 = eps_list.index(0.20)
print(f"Attack success (eps=0.20): FGSM {100 - fgsm_accs[i20]:.1f} %, "
      f"PGD {100 - pgd_accs[i20]:.1f} %\n")

# =============== TASK 5: Adversarial training ===============
print("Adversarial fine-tuning (2 epochs, 50:50 clean + FGSM eps=0.20)...")
robust = copy.deepcopy(base)
train(robust, epochs=2, adv_eps=0.20)
print("done.\n")

b_clean, b_fgsm, b_pgd = clean_acc, fgsm_accs[i20], pgd_accs[i20]
r_clean = evaluate(robust)
r_fgsm = evaluate(robust, fgsm, 0.20)
r_pgd = evaluate(robust, pgd, 0.20)

print("MODEL              CLEAN    FGSM(0.20)   PGD(0.20)")
print("----------------------------------------------------")
print(f"Baseline           {b_clean:5.1f} %    {b_fgsm:5.1f} %     {b_pgd:5.1f} %")
print(f"Adversarially      {r_clean:5.1f} %    {r_fgsm:5.1f} %     {r_pgd:5.1f} %")
print("trained")
print("----------------------------------------------------")
print(f"Clean accuracy change : {r_clean - b_clean:+.1f} %")
print(f"FGSM robustness gain  : {r_fgsm - b_fgsm:+.1f} %    PGD gain : {r_pgd - b_pgd:+.1f} %")

# =============== TASK 6: Accuracy vs epsilon plot ===============
plt.figure(figsize=(7, 5))
plt.plot(eps_list, fgsm_accs, "o-", label="FGSM (baseline)")
plt.plot(eps_list, pgd_accs, "s-", label="PGD (baseline)")
plt.xlabel("Epsilon (L-inf perturbation size)")
plt.ylabel("Test accuracy (%)")
plt.title("Baseline model: accuracy vs epsilon")
plt.grid(True)
plt.legend()
plt.savefig("accuracy_vs_epsilon.png", dpi=150)
plt.close()
print("Plot saved : accuracy_vs_epsilon.png")

